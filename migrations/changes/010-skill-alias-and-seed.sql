--changeset tracing-ats:010-skill-alias
-- Словарь синонимов: точное совпадение нормализованного названия.
-- Каноническое имя навыка тоже хранится алиасом к самому себе.
CREATE TABLE skill_alias (
    id               uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    alias_normalized varchar(128) NOT NULL,
    skill_id         uuid         NOT NULL REFERENCES skill (id) ON DELETE CASCADE,
    source           varchar(8)   NOT NULL,
    CONSTRAINT uq_skill_alias UNIQUE (alias_normalized),
    CONSTRAINT ck_skill_alias_source CHECK (source IN ('SEED', 'HR'))
);

-- Бэкфилл для навыков, созданных до появления словаря.
INSERT INTO skill_alias (alias_normalized, skill_id, source)
SELECT normalized_name, id, 'SEED'
FROM skill
ON CONFLICT (alias_normalized) DO NOTHING;
